"""Reincarnation, death record, and legacy schemas."""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from app.models.enums import (
    BackgroundName,
    DeathCause,
    GenderPresentation,
    LegacyType,
    RaceName,
)


class DeathRecordRequest(BaseModel):
    """Request payload to record a character's death."""

    character_id: int = Field(..., description="ID of the character dying")
    cause: DeathCause = Field(
        default=DeathCause.EVENT_CONSEQUENCES,
        description="Authoritative cause of death",
    )
    death_description: str | None = Field(
        default=None, description="Optional narrative description of the death"
    )


class LifeRecordResponse(BaseModel):
    """Complete soul record of a deceased character's life."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    session_id: int
    character_id: int
    generation: int
    name: str
    race_name: RaceName
    background_name: BackgroundName
    gender_presentation: GenderPresentation
    age_at_death: int
    cause_of_death: DeathCause
    death_description: str
    days_lived: int
    final_attributes: dict[str, int]
    final_skills: dict[str, int]
    final_money: int
    final_inventory: list[dict[str, Any]]
    final_relationships: dict[str, int]
    important_decisions: list[dict[str, Any]]
    achievements: list[str]
    created_at: datetime | None = None


class CharacterLegacyResponse(BaseModel):
    """Legacy generated by a deceased character to pass to the next life."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    character_id: int
    legacy_type: LegacyType
    description: str
    attribute_bonus: str | None = None
    attribute_bonus_value: int = 0
    skill_affinity: str | None = None
    skill_affinity_bonus: int = 0
    memory_fragment: str | None = None
    recurring_dream: str | None = None
    created_at: datetime | None = None


class DeathSummaryResponse(BaseModel):
    """Response returned upon recording character death."""

    message: str
    character_id: int
    is_alive: bool
    life_record: LifeRecordResponse
    legacy: CharacterLegacyResponse


class LifeRecordListResponse(BaseModel):
    """Collection of life records for a game session."""

    session_token: str
    total_records: int
    records: list[LifeRecordResponse]
