"""Reincarnation and death API router."""

from fastapi import APIRouter, Depends, Query, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db_session
from app.core.exceptions import NotFoundError
from app.schemas.reincarnation import (
    CharacterLegacyResponse,
    DeathRecordRequest,
    DeathSummaryResponse,
    LifeRecordListResponse,
    LifeRecordResponse,
)
from app.services.reincarnation.death import (
    get_legacy_by_character,
    get_life_record_by_character,
    get_session_life_records,
    record_death,
)

router = APIRouter(prefix="/reincarnation", tags=["reincarnation"])


@router.post(
    "/death",
    response_model=DeathSummaryResponse,
    status_code=status.HTTP_200_OK,
    summary="Record character death and generate life record & legacy",
)
async def record_character_death(
    request: DeathRecordRequest,
    session: AsyncSession = Depends(get_db_session),
) -> DeathSummaryResponse:
    """
    Authoritatively record character death.

    Creates the soul record (LifeRecord) and generates a limited legacy
    (CharacterLegacy) according to AGENTS.md §14 and SPEC §9.
    """
    character, life_record, legacy = await record_death(
        session=session,
        character_id=request.character_id,
        cause=request.cause,
        death_description=request.death_description,
    )
    return DeathSummaryResponse(
        message=f"{character.name} has perished. Soul record and legacy generated.",
        character_id=character.id,
        is_alive=character.is_alive,
        life_record=LifeRecordResponse.model_validate(life_record),
        legacy=CharacterLegacyResponse.model_validate(legacy),
    )


@router.get(
    "/life-record/{character_id}",
    response_model=LifeRecordResponse,
    summary="Retrieve soul record for a deceased character",
)
async def get_character_life_record(
    character_id: int,
    session: AsyncSession = Depends(get_db_session),
) -> LifeRecordResponse:
    """Retrieve the authoritative LifeRecord for a character."""
    life_record = await get_life_record_by_character(session, character_id)
    if life_record is None:
        raise NotFoundError("LifeRecord", f"character_id={character_id}")
    return LifeRecordResponse.model_validate(life_record)


@router.get(
    "/legacy/{character_id}",
    response_model=CharacterLegacyResponse,
    summary="Retrieve legacy generated by a character",
)
async def get_character_legacy_endpoint(
    character_id: int,
    session: AsyncSession = Depends(get_db_session),
) -> CharacterLegacyResponse:
    """Retrieve the CharacterLegacy created by a character."""
    legacy = await get_legacy_by_character(session, character_id)
    if legacy is None:
        raise NotFoundError("CharacterLegacy", f"character_id={character_id}")
    return CharacterLegacyResponse.model_validate(legacy)


@router.get(
    "/records",
    response_model=LifeRecordListResponse,
    summary="Retrieve all soul records for a session",
)
async def get_session_records(
    session_token: str = Query(..., description="Unique session token"),
    session: AsyncSession = Depends(get_db_session),
) -> LifeRecordListResponse:
    """Retrieve all LifeRecords for the specified session in chronological generation order."""
    records = await get_session_life_records(session, session_token)
    return LifeRecordListResponse(
        session_token=session_token,
        total_records=len(records),
        records=[LifeRecordResponse.model_validate(r) for r in records],
    )
